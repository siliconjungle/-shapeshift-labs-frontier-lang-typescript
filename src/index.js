function safeIdentifier(name) {
  const identifier = name.replace(/[^A-Za-z0-9_$]/g, '_');
  return /^[A-Za-z_$]/.test(identifier) ? identifier : `_${identifier}`;
}

function toTypeScriptType(type) {
  const primitive = { Text: 'string', String: 'string', Bool: 'boolean', Boolean: 'boolean', Int: 'number', Float: 'number', Number: 'number', Instant: 'string', Json: 'unknown', Patch: 'FrontierPatchOperation[]' };
  if (!type) return 'unknown';
  if (typeof type !== 'string') {
    if (type.kind === 'ref') return `${safeIdentifier(type.name)}${type.args?.length ? `<${type.args.map(toTypeScriptType).join(', ')}>` : ''}`;
    if (type.kind === 'set') return `ReadonlySet<${toTypeScriptType(type.item)}>`;
    if (type.kind === 'list') return `readonly ${toTypeScriptType(type.item)}[]`;
    if (type.kind === 'map') return `ReadonlyMap<${toTypeScriptType(type.key)}, ${toTypeScriptType(type.value)}>`;
    if (type.kind === 'record') return `{ ${type.fields.map((field) => `${safeIdentifier(field.name)}${field.optional ? '?' : ''}: ${toTypeScriptType(field.type)}`).join('; ')} }`;
    if (type.kind === 'union') return type.variants.map((variant) => {
      const fields = variant.fields?.length ? ` & { ${variant.fields.map((field) => `${safeIdentifier(field.name)}${field.optional ? '?' : ''}: ${toTypeScriptType(field.type)}`).join('; ')} }` : '';
      return `{ kind: ${JSON.stringify(variant.name)} }${fields}`;
    }).join(' | ') || 'never';
    return 'unknown';
  }
  if (primitive[type]) return primitive[type];
  const setMatch = /^Set<(.+)>$/.exec(type);
  if (setMatch) return `ReadonlySet<${toTypeScriptType(setMatch[1].trim())}>`;
  const listMatch = /^(List|MoveList)<(.+)>$/.exec(type);
  if (listMatch) return `readonly ${toTypeScriptType(listMatch[2].trim())}[]`;
  const mapMatch = /^Map<(.+),(.+)>$/.exec(type);
  if (mapMatch) return `ReadonlyMap<${toTypeScriptType(mapMatch[1].trim())}, ${toTypeScriptType(mapMatch[2].trim())}>`;
  if (/^\{.*\}$/.test(type)) return 'Record<string, unknown>';
  return safeIdentifier(type);
}

function sourceRef(node, extra = {}) {
  return {
    semanticNodeId: node.id,
    semanticNodeKind: node.kind,
    semanticNodeName: node.name,
    ...extra
  };
}

export function toTypeScriptAst(document, options = {}) {
  const banner = options.banner ?? 'Generated by @shapeshift-labs/frontier-lang-typescript.';
  const declarations = [];
  if (options.includeRuntimeTypes ?? true) {
    declarations.push({ kind: 'runtimeTypes' });
  }
  for (const node of Object.values(document.nodes)) {
    if (node.kind === 'type') declarations.push(typeNodeToAst(node));
  }
  for (const node of Object.values(document.nodes)) {
    if (node.kind === 'lattice') {
      declarations.push({
        kind: 'latticeDescriptor',
        name: `${safeIdentifier(node.name)}Lattice`,
        value: {
          name: node.name,
          carrier: toTypeScriptType(node.carrier),
          laws: node.laws ?? [],
          frontierCrdt: node.frontierCrdt
        },
        sourceRef: sourceRef(node)
      });
    }
  }
  for (const node of Object.values(document.nodes)) {
    if (node.kind === 'capability') {
      declarations.push({
        kind: 'capabilityDescriptor',
        name: `${safeIdentifier(node.name)}Capability`,
        value: {
          capability: node.capability,
          category: node.category,
          input: node.input ? toTypeScriptType(node.input) : undefined,
          returns: node.returns ? toTypeScriptType(node.returns) : undefined,
          effects: node.effects ?? [],
          resources: node.resources ?? [],
          adapters: node.adapters ?? [],
          unsupportedTargets: node.unsupportedTargets ?? []
        },
        sourceRef: sourceRef(node)
      });
    }
  }
  for (const node of Object.values(document.nodes)) {
    if (node.kind === 'entity') declarations.push({
      kind: 'interface',
      name: safeIdentifier(node.name),
      fields: node.fields.map((field) => ({ name: safeIdentifier(field.name), type: toTypeScriptType(field.type), optional: false })),
      sourceRef: sourceRef(node, { regionIds: node.fields.map((field) => field.id) })
    });
  }
  for (const node of Object.values(document.nodes)) {
    if (node.kind === 'state') declarations.push({
      kind: 'interface',
      name: `${safeIdentifier(node.name)}State`,
      fields: node.collections.map((collection) => ({ name: safeIdentifier(collection.name), type: toTypeScriptType(collection.type), optional: false })),
      sourceRef: sourceRef(node, { regionIds: node.collections.map((collection) => collection.id) })
    });
  }
  for (const node of Object.values(document.nodes)) {
    if (node.kind === 'extern') {
      declarations.push({
        kind: 'externFunction',
        name: safeIdentifier(node.name),
        inputType: node.signature?.input ? toTypeScriptType(node.signature.input) : 'unknown',
        returnType: node.signature?.returns ? toTypeScriptType(node.signature.returns) : 'unknown',
        sourceRef: sourceRef(node)
      });
    }
  }
  for (const node of Object.values(document.nodes)) {
    if (node.kind === 'action') {
      declarations.push({
        kind: 'actionFunction',
        name: safeIdentifier(node.name),
        inputType: node.input ? toTypeScriptType(node.input) : 'unknown',
        returnType: node.returns ? toTypeScriptType(node.returns) : 'FrontierPatchOperation[]',
        sourceRef: sourceRef(node)
      });
    }
  }
  return { kind: 'typescript.module', banner, declarations };
}

export function renderTypeScriptAst(ast) {
  const lines = [];
  lines.push(`// ${ast.banner}`, '');
  for (const declaration of ast.declarations) {
    if (declaration.kind === 'runtimeTypes') {
      lines.push('export type FrontierPatchOperation =', "  | { op: 'set'; path: string; value: unknown }", "  | { op: 'remove'; path: string }", "  | { op: 'insert'; path: string; value: unknown }", "  | { op: 'merge'; path: string; value: unknown };", '');
      lines.push('export interface FrontierLatticeDescriptor {', '  readonly name: string;', '  readonly carrier: string;', '  readonly laws: readonly string[];', '  readonly frontierCrdt?: { readonly packageName?: string; readonly exportName: string; readonly lawChecker?: string };', '}', '');
      lines.push('export interface FrontierCapabilityDescriptor {', '  readonly capability: string;', '  readonly category?: string;', '  readonly input?: string;', '  readonly returns?: string;', '  readonly effects: readonly string[];', '  readonly resources: readonly string[];', '  readonly adapters: readonly unknown[];', '  readonly unsupportedTargets: readonly unknown[];', '}', '');
    }
    if (declaration.kind === 'typeAlias') {
      lines.push(`export type ${declaration.name}${declaration.parameters} = ${declaration.type};`, '');
    }
    if (declaration.kind === 'interface') {
      lines.push(`export interface ${declaration.name}${declaration.parameters ?? ''} {`);
      for (const field of declaration.fields) lines.push(`  ${field.name}${field.optional ? '?' : ''}: ${field.type};`);
      lines.push('}', '');
    }
    if (declaration.kind === 'latticeDescriptor') {
      lines.push(`export const ${declaration.name}: FrontierLatticeDescriptor = {`);
      lines.push(`  name: ${JSON.stringify(declaration.value.name)},`);
      lines.push(`  carrier: ${JSON.stringify(declaration.value.carrier)},`);
      lines.push(`  laws: ${JSON.stringify(declaration.value.laws)},`);
      if (declaration.value.frontierCrdt) lines.push(`  frontierCrdt: ${JSON.stringify(declaration.value.frontierCrdt)}`);
      lines.push('};', '');
    }
    if (declaration.kind === 'capabilityDescriptor') {
      lines.push(`export const ${declaration.name}: FrontierCapabilityDescriptor = ${JSON.stringify(declaration.value, null, 2)};`, '');
    }
    if (declaration.kind === 'externFunction') {
      lines.push(`export declare function ${declaration.name}(input: ${declaration.inputType}): ${declaration.returnType};`, '');
    }
    if (declaration.kind === 'actionFunction') {
      lines.push(`export function ${declaration.name}(`, '  state: unknown,', `  input: ${declaration.inputType},`, '  env: Record<string, unknown> = {}', `): ${declaration.returnType} {`, '  void state;', '  void input;', '  void env;', `  return [] as ${declaration.returnType};`, '}', '');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

export function emitTypeScript(document, options = {}) {
  return renderTypeScriptAst(toTypeScriptAst(document, options));
}

function typeNodeToAst(node) {
  const params = node.parameters?.length ? `<${node.parameters.map(safeIdentifier).join(', ')}>` : '';
  if (node.type) {
    return { kind: 'typeAlias', name: safeIdentifier(node.name), parameters: params, type: toTypeScriptType(node.type), sourceRef: sourceRef(node) };
  }
  if (node.variants?.length) {
    return { kind: 'typeAlias', name: safeIdentifier(node.name), parameters: params, type: toTypeScriptType({ kind: 'union', variants: node.variants }), sourceRef: sourceRef(node) };
  }
  return {
    kind: 'interface',
    name: safeIdentifier(node.name),
    parameters: params,
    fields: (node.fields ?? []).map((field) => ({ name: safeIdentifier(field.name), type: toTypeScriptType(field.type), optional: Boolean(field.optional) })),
    sourceRef: sourceRef(node, { regionIds: (node.fields ?? []).map((field) => field.id) })
  };
}
